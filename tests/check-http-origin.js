/* InkWeft S1 sample — HTTP origin evidence path check.

   The plan's S1 exit requires a REAL persistence origin and refuses in-memory
   substitutes (docs/05 §2). This exercises the piece of that claim the sample can
   actually make offline: over a real HTTP origin the app re-reads the source PDF
   bytes and recomputes the recorded SHA-256, so "the original did not change" is
   checked against bytes rather than against a number we wrote ourselves.

   It does NOT test IndexedDB, a native store, or durability. Those stay NOT_RUN.

   Usage:  python tools/serve.py 8777   (in another terminal)
           node tests/check-http-origin.js [port]
*/
'use strict';

const path = require('path');
const fs = require('fs');

const ROOT = path.resolve(__dirname, '..');
for (const f of ['00-core.js', '10-vault.js', '20-document.js', '30-commands.js',
                 '40-store.js', '50-export.js', '60-seed.js']) {
  require(path.join(ROOT, 'src', f));
}
const IW = globalThis.IW;

const port = process.argv[2] || '8777';
const base = `http://127.0.0.1:${port}`;

const local = fs.readFileSync(path.join(ROOT, 'assets', 'conditional-probability-note.pdf'));
const localSha = IW.sha256Hex(new Uint8Array(local));

const problems = [];
function check(name, fn) { try { fn(); } catch (e) { problems.push(name + ': ' + e.message); } }

(async () => {
  let index;
  try {
    index = await fetch(`${base}/index.html`);
  } catch (e) {
    console.error(`cannot reach ${base} — start it with:  python tools/serve.py ${port}`);
    process.exit(2);
  }

  check('index.html is served', () => {
    if (!index.ok) throw new Error('HTTP ' + index.status);
  });

  const html = await index.text();
  check('the served page is the built sample', () => {
    if (html.indexOf('InkWeft S1 sample — generated by tools/build.js') < 0) {
      throw new Error('generated-file banner missing; rebuild with node tools/build.js');
    }
    if (html.indexOf('<script>') < 0) throw new Error('inline script missing');
  });

  const pdfRes = await fetch(`${base}/assets/conditional-probability-note.pdf`);
  check('the PDF asset is served', () => {
    if (!pdfRes.ok) throw new Error('HTTP ' + pdfRes.status);
  });

  const bytes = new Uint8Array(await pdfRes.arrayBuffer());
  const servedSha = IW.sha256Hex(bytes);
  check('served bytes hash to the same value as the file on disk', () => {
    if (servedSha !== localSha) throw new Error(`served ${servedSha} != local ${localSha}`);
  });
  check('the served bytes are a PDF', () => {
    const head = String.fromCharCode.apply(null, bytes.slice(0, 5));
    if (head !== '%PDF-') throw new Error('magic is ' + JSON.stringify(head));
  });

  /* End to end: seed a vault that records this hash, then re-resolve it. */
  const corpus = IW.corpus();
  let engine;
  let seamOK = false;
  try {
    engine = IW.createEngine({ vaultId: 'http-origin-check' });
    let n = 0;
    const header = () => IW.commandHeader('http-' + (++n), engine);
    for (const step of IW.seedPlan(corpus, { pdfSha256: servedSha, pdfBytes: bytes.length })) {
      engine.run(step.command, step.params, header());
    }
    const surface = IW.createSurface(IW.originFor(corpus.text), {
      docId: corpus.text.id,
      docIndex: () => engine.getVault().documents,
      versionIndex: () => engine.getVault().documentVersions,
      grants: engine.grants
    });
    const seeded = IW.createFirstCard(engine, surface, corpus.text, IW.defaultSelection(corpus));
    seamOK = !!seeded.receipt.result.cardId;
  } catch (e) {
    seamOK = false;
    problems.push('seed over an HTTP-verified asset failed: ' + (e.code || e.message));
  }
  check('a card can be seeded from a source whose bytes were verified over HTTP', () => {
    if (!seamOK) throw new Error('seeding failed');
  });

  const recorded = engine.getVault().documentVersions.find((v) => v.kind === 'pdf-origin');
  check('the recorded hash equals the hash of bytes fetched over HTTP', () => {
    if (!recorded || recorded.sha256 !== servedSha) throw new Error('recorded hash differs');
  });

  if (problems.length) {
    console.error('HTTP ORIGIN CHECK FAILED');
    for (const p of problems) console.error('  - ' + p);
    process.exit(1);
  }
  console.log('HTTP ORIGIN CHECK PASSED');
  console.log(`  origin      ${base}`);
  console.log(`  pdf bytes   ${bytes.length}`);
  console.log(`  sha256      ${servedSha}`);
  console.log('  note        this covers the HTTP origin and byte verification only.');
  console.log('              IndexedDB/native persistence and durability remain NOT_RUN.');
})();
